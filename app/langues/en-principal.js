// « aujourd'hui », « hier », « il y a 3 jours », « 3 jours » → anglais.
function enP_duree(s) {
  s = String(s).trim();
  if (s === "aujourd'hui") return "today";
  if (s === "hier") return "yesterday";
  let m = s.match(/^il y a (\d+) jours?$/);
  if (m) return m[1] + (m[1] === "1" ? " day ago" : " days ago");
  m = s.match(/^(\d+) jours?$/);
  if (m) return m[1] + (m[1] === "1" ? " day" : " days");
  return tr(s);
}
// « Doit depuis 3 jours » : since / for.
function enP_depuis(s) {
  s = String(s).trim();
  if (s === "aujourd'hui") return "since today";
  if (s === "hier") return "since yesterday";
  return "for " + enP_duree(s);
}

